/** Runtime translate seat, bound by the browser entry. */
let runtimeTranslate: ((key: OpsKey) => string) | undefined

/** Bind the locale service's translator for this namespace. */
export function setRuntimeTranslate(translate: (key: OpsKey) => string): void {
  runtimeTranslate = translate
}

/** Translate one key, falling back to Chinese then the key itself. */
export function tt(key: OpsKey, vars?: Record<string, string | number>): string {
  const raw = runtimeTranslate?.(key) ?? zh[key] ?? key
  if (vars === undefined) return raw
  return raw.replace(/\{(\w+)\}/g, (match, name: string) => (vars[name] === undefined ? match : String(vars[name])))
}
